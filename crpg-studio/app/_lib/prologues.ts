// An AI-written main story, saved in the game. `text` is the story in the same line format as genre-reference.json
// mains (필요 세력 / 필수 NPC / 시작 계기 / "- N막 이름:" lines / 흑막 / 최종 보스 / 최종 목표(...)), so the GM prompt,
// promptUpToAct and the goal steps treat it exactly like a fixed story.
export type GeneratedStory = { name: string; city: string; text: string; progressSteps: string[]; prologue: MainPrologue; createdAt: number };
// A game's own story when it has one for the chosen main, else the fixed story of that name.
type StoryOwner = { wizardMain?: string; mainStory?: GeneratedStory };
export const mainPrologue = (main?: string | StoryOwner): MainPrologue | undefined => {
  if (main && typeof main === 'object') return main.mainStory && main.mainStory.name === main.wizardMain ? main.mainStory.prologue : mainPrologue(main.wizardMain);
  return main ? MAIN_PROLOGUES[main] : undefined;
};
// The whole main quest line, first errand included; undefined for stories that have no chain yet.
export const mainChain = (main?: string | StoryOwner): MainStep[] | undefined => {
  const p = mainPrologue(main);
  return p?.questChain?.length ? [{ q: p.firstQuest, beats: p.firstBeats }, ...p.questChain] : undefined;
};
